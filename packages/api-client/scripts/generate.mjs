import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

process.stdin.setEncoding("utf8");
let schema = "";
for await (const chunk of process.stdin) {
  schema += chunk;
}

const types = "// Generated by pnpm api:generate. Do not edit.\n"
  + astToString(await openapiTS(JSON.parse(schema), { defaultNonNullable: false }));
const artifacts = [
  [new URL("../openapi.json", import.meta.url), schema],
  [new URL("../src/schema.ts", import.meta.url), types],
];

for (const [path, content] of artifacts) {
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8");
    if (current.replaceAll("\r\n", "\n") !== content.replaceAll("\r\n", "\n")) {
      console.error(`${path.pathname} kedaluwarsa. Jalankan pnpm api:generate.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(path, content);
  }
}
